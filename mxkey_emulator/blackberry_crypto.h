static const int MEP_KEYS_COUNT = sizeof(MEP_KEYS)/sizeof(MepKey);

BOOL HmacSha1Compute(
    const BYTE key[16],
    const BYTE* data,
    DWORD dataLen,
    BYTE digest[20])
{
    HCRYPTPROV hProv = 0;
    HCRYPTKEY hKey = 0;
    HCRYPTHASH hHash = 0;
    DWORD dwHashLen = 20;
    BOOL result = FALSE;
    KEYBLOB blob;
    HMAC_INFO hmacInfo;

    if (!key || !data || !digest)
    {
        return FALSE;
    }

    if (!CryptAcquireContext(
            &hProv,
            NULL,
            MS_ENHANCED_PROV,
            PROV_RSA_FULL,
            CRYPT_VERIFYCONTEXT))
    {
        goto cleanup;
    }

    ZeroMemory(&blob, sizeof(blob));
    blob.hdr.bType = PLAINTEXTKEYBLOB;
    blob.hdr.bVersion = CUR_BLOB_VERSION;
    blob.hdr.reserved = 0;
    blob.hdr.aiKeyAlg = CALG_RC2;
    blob.dwKeySize = 16;
    memcpy(blob.rgbKeyData, key, 16);

    if (!CryptImportKey(hProv, (BYTE*)&blob, sizeof(blob), 0, CRYPT_IPSEC_HMAC_KEY, &hKey))
        goto cleanup;

    ZeroMemory(&hmacInfo, sizeof(HMAC_INFO));
    hmacInfo.HashAlgid = CALG_SHA1;

    if (!CryptCreateHash(hProv, CALG_HMAC, hKey, 0, &hHash))
        goto cleanup;

    if (!CryptSetHashParam(hHash, HP_HMAC_INFO, (BYTE*)&hmacInfo, 0))
        goto cleanup;

    if (!CryptHashData(hHash, data, dataLen, 0))
        goto cleanup;

    if (!CryptGetHashParam(hHash, HP_HASHVAL, digest, &dwHashLen, 0))
        goto cleanup;

    result = TRUE;

cleanup:
    if (hHash) CryptDestroyHash(hHash);
    if (hKey)  CryptDestroyKey(hKey);
    if (hProv) CryptReleaseContext(hProv, 0);

    return result;
}

BOOL CalculateMep(const char* mepName, BYTE imei[16], BYTE outBuffer[20])
{
    BOOL result = FALSE;
    for (int i = 0; i < MEP_KEYS_COUNT; i++)
    {
        if (strcmp(MEP_KEYS[i].name, mepName) == 0)
        {
            result = HmacSha1Compute(MEP_KEYS[i].key, imei, 16, outBuffer);
            for (int j = 0; j < 20; j++)
                outBuffer[j] = outBuffer[j] % 10;
            break;
        }
    }

    return result;
}